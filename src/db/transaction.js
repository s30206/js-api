// Runs callback(client) inside BEGIN/COMMIT on one pooled client; any thrown error rolls the transaction back.
export function createWithTransaction({ pool }) {
  return async function withTransaction(callback) {
    const client = await pool.connect();
    try {
      await client.query('BEGIN');
      const result = await callback(client);
      await client.query('COMMIT');
      return result;
    } catch (error) {
      await client.query('ROLLBACK');
      throw error;
    } finally {
      client.release();
    }
  };
}
